// Optional UI integration test. Requires @playwright/test and its Chromium browser.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'@playwright/test');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'vv-gpt4-ui-'));
const port=5064,url=`http://127.0.0.1:${port}`;
const server=spawn(path.join(root,'.venv/bin/python'),['app.py'],{cwd:root,env:{...process.env,VVGPT_PORT:String(port),VVGPT_DATA:temporary},stdio:'ignore'});
let browser;
(async()=>{
  let ready=false;
  for(let i=0;i<60;i++){try{const r=await fetch(url+'/health');if(r.ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,100));}
  assert(ready,'Test server did not start');
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:950}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto(url);
  await page.waitForFunction(()=>document.querySelector('#engine-state').textContent.includes('available'));
  await page.screenshot({path:path.join(root,'docs/assistant-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Knowledge',exact:false}).click();
  await page.locator('#knowledge-file').setInputFiles({name:'alder-ui-test.txt',mimeType:'text/plain',buffer:Buffer.from('Project Alder launches on 23 February 2027. Its budget is 450 pounds.')});
  await page.getByText('alder-ui-test.txt',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Assistant',exact:false}).click();
  await page.locator('#prompt').fill('When does Project Alder launch? Answer one sentence and cite the source.');
  await page.locator('#send').click();
  await page.waitForFunction(()=>!document.querySelector('#send').disabled,{},{timeout:90000});
  assert.match(await page.locator('.message.assistant .body').last().innerText(),/23 February 2027/);
  assert.match(await page.locator('.sources').last().innerText(),/alder-ui-test/);
  await page.reload();
  await page.locator('#history button').first().click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===2);
  assert.equal(await page.locator('.message').count(),2);
  await page.getByRole('button',{name:'Training lab',exact:false}).click();
  await page.locator('#dataset-file').setInputFiles({name:'ui-smoke.txt',mimeType:'text/plain',buffer:Buffer.from('A river flows through the valley. The village sleeps beneath the stars.\n'.repeat(400))});
  await page.waitForFunction(()=>document.querySelector('#dataset option').value!=='');
  await page.locator('[name=name]').fill('UI smoke only');
  await page.locator('[name=steps]').fill('6');
  await page.getByText('Training settings',{exact:true}).click();
  await page.locator('[name=context]').fill('32');
  await page.locator('[name=batch]').fill('2');
  await page.locator('[name=eval_every]').fill('2');
  await page.getByRole('button',{name:'Start training',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#run-status').textContent==='completed',{},{timeout:90000});
  assert.equal(await page.locator('#run-step').innerText(),'6 / 6');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(root,'docs/lab-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'My models',exact:false}).click();
  await page.locator('#refresh').click();
  await page.locator('#model-library').getByText('UI smoke only',{exact:true}).waitFor();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(root,'docs/models-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Preferences',exact:false}).click();
  await page.locator('#memory').fill('Keep answers concise.');
  await page.getByRole('button',{name:'Save preferences'}).click();
  await page.reload();await page.getByRole('button',{name:'Preferences',exact:false}).click();
  await page.waitForFunction(()=>document.querySelector('#memory').value==='Keep answers concise.');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#new-chat').click();
  await page.screenshot({path:path.join(root,'docs/assistant-mobile.png'),fullPage:true});
  const options=await page.locator('#mobile-history option').count();assert(options>1);
  await page.locator('#mobile-history').selectOption({index:1});
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===2);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  const report={date:'2026-11-17',passed:true,checks:['real local chat through UI','source display','conversation persistence','dataset import','real six-step training through UI','run graph rendering','model discovery','preference persistence','mobile history access','no horizontal overflow','no browser console errors']};
  fs.writeFileSync(path.join(root,'docs/ui-verification.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  if(browser)await browser.close();server.kill('SIGTERM');
  // Preserve failed-run diagnostics; remove only this script's completed temporary workspace.
  if(!process.exitCode)fs.rmSync(temporary,{recursive:true,force:true});
});
